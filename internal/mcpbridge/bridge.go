package mcpbridge

import (
	"context"
	"errors"
	"net/http"
	"strings"
	"time"

	"cyberforge/gateway/internal/mcphttp"
	"cyberforge/gateway/internal/requestid"
	"github.com/modelcontextprotocol/go-sdk/jsonrpc"
	"github.com/modelcontextprotocol/go-sdk/mcp"
)

func (b *Bridge) buildHandler() (handler http.Handler, err error) {
	// The SDK validates schema header extensions at registration and reports bad
	// definitions by panic. Treat these as sanitized startup errors, not a crash.
	defer func() {
		if recover() != nil {
			handler = nil
			err = errors.New("catalog_sdk_registration_failed")
		}
	}()
	server := mcp.NewServer(&mcp.Implementation{Name: "cyberforge-gateway", Version: "0.2.0"}, mcphttp.ServerOptions())
	for _, entry := range b.entries {
		server.AddTool(entry.tool, func(ctx context.Context, req *mcp.CallToolRequest) (*mcp.CallToolResult, error) {
			return b.forward(ctx, entry, req)
		})
	}
	server.AddReceivingMiddleware(func(next mcp.MethodHandler) mcp.MethodHandler {
		return func(ctx context.Context, method string, req mcp.Request) (mcp.Result, error) {
			switch method {
			case "server/discover", "tools/list":
				return next(ctx, method, req)
			case "tools/call":
				call, ok := req.(*mcp.CallToolRequest)
				if !ok || call.Params == nil {
					return nil, rpcError(jsonrpc.CodeInvalidParams, "invalid_request")
				}
				if _, known := b.entries[call.Params.Name]; !known {
					b.logCall(ctx, nil, "invalid_request", "unknown_tool", time.Now())
					return nil, rpcError(jsonrpc.CodeInvalidParams, "unknown_tool")
				}
				return next(ctx, method, req)
			default:
				return nil, rpcError(jsonrpc.CodeMethodNotFound, "method_not_supported")
			}
		}
	})
	return mcp.NewStreamableHTTPHandler(func(*http.Request) *mcp.Server { return server }, &mcp.StreamableHTTPOptions{
		Stateless: true, MaxRequestBodyBytes: b.cfg.MCPMaxRequestBytes, PropagateRequestCancellation: true,
	}), nil
}

func rpcError(code int64, reason string) error { return &jsonrpc.Error{Code: code, Message: reason} }

func (b *Bridge) forward(ctx context.Context, entry *entry, req *mcp.CallToolRequest) (_ *mcp.CallToolResult, err error) {
	started := time.Now()
	outcome, reason := "succeeded", "ok"
	defer func() { b.logCall(ctx, entry, outcome, reason, started) }()
	if !b.Ready() {
		outcome, reason = "upstream_unavailable", "upstream_unavailable"
		return nil, rpcError(-32000, reason)
	}
	if len(req.Params.InputResponses) != 0 || req.Params.RequestState != "" || !validArguments(req.Params.Arguments, entry.input) {
		outcome, reason = "invalid_request", "invalid_arguments"
		return nil, rpcError(jsonrpc.CodeInvalidParams, reason)
	}
	callCtx, cancel := context.WithTimeout(ctx, b.cfg.MCPCallTimeout)
	defer cancel()
	stop := context.AfterFunc(b.lifetime, cancel)
	defer stop()
	// RawMessage preserves numbers and nested arguments; protocol metadata and
	// headers are regenerated by the SDK for the translated upstream name.
	result, e := b.session.CallTool(callCtx, &mcp.CallToolParams{Name: entry.original, Arguments: req.Params.Arguments})
	if e != nil {
		switch {
		case errors.Is(callCtx.Err(), context.DeadlineExceeded):
			outcome, reason = "deadline_exceeded", "upstream_deadline_exceeded"
		case errors.Is(callCtx.Err(), context.Canceled):
			outcome, reason = "cancelled", "request_cancelled"
		default:
			var protocolErr *jsonrpc.Error
			// The SDK also wraps network/HTTP failures in its transport-rejected
			// JSON-RPC sentinel (-32005). Only peer protocol errors are nonfatal.
			if errors.As(e, &protocolErr) && protocolErr.Code >= -32700 && protocolErr.Code <= -32600 {
				outcome, reason = "tool_error", "upstream_protocol_error"
			} else {
				b.available.Store(false)
				outcome, reason = "upstream_unavailable", "upstream_unavailable"
			}
		}
		return nil, rpcError(-32000, reason)
	}
	if result == nil || result.NeedsInput() || len(result.InputRequests) > 0 {
		outcome, reason = "tool_error", "unsupported_upstream_result"
		return nil, rpcError(-32000, reason)
	}
	if !result.IsError && entry.output != nil && (result.StructuredContent == nil || entry.output.Validate(result.StructuredContent) != nil) {
		outcome, reason = "tool_error", "invalid_upstream_result"
		return nil, rpcError(-32000, reason)
	}
	if result.IsError {
		outcome, reason = "tool_error", "upstream_tool_error"
	}
	// Only our application-owned metadata namespace has defined bridge semantics.
	meta := mcp.Meta{}
	for key, value := range result.Meta {
		if strings.HasPrefix(key, "com.cyberforge/") {
			meta[key] = value
		}
	}
	return &mcp.CallToolResult{Content: result.Content, StructuredContent: result.StructuredContent, IsError: result.IsError, Meta: meta}, nil
}

func (b *Bridge) logCall(ctx context.Context, entry *entry, outcome, reason string, started time.Time) {
	name, original := "unknown", "unknown"
	if entry != nil {
		name, original = entry.tool.Name, entry.original
	}
	b.logger.Info("mcp_call_completed", "request_id", requestid.From(ctx), "upstream_id", b.cfg.MCPUpstreamID, "tool", name, "original_tool", original, "outcome", outcome, "reason_code", reason, "duration_ms", float64(time.Since(started))/float64(time.Millisecond))
}
